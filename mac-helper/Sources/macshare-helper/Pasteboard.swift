// Watches NSPasteboard.changeCount (cheap) so main reads the text only when it changed, and tells
// whether the item is marked concealed/transient by a password manager (nspasteboard.org types).
import Cocoa

final class PasteboardWatch {
  private var timer: Timer?
  private var lastCount = -1     // last count we emitted
  private var seenCount = -1     // count seen on the previous tick (emit once it is stable)
  private var first = true
  private static let privateTypes: Set<String> = [
    "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
  ]

  static func info() -> [String: Any] {
    let pb = NSPasteboard.general
    let types = Set((pb.types ?? []).map { $0.rawValue })
    return ["changeCount": pb.changeCount, "concealed": !types.isDisjoint(with: privateTypes)]
  }

  func set(on: Bool) {
    timer?.invalidate()
    timer = nil
    lastCount = -1
    seenCount = -1
    first = true
    guard on else { return }
    check()
    timer = Timer.scheduledTimer(withTimeInterval: 0.25, repeats: true) { [weak self] _ in self?.check() }
    timer?.tolerance = 0.05 // macOS may run it with other wakeups
  }

  private func check() {
    // Apps write an item in several steps (clear, declare types, set data); wait until the
    // count is the same on two ticks so the concealed flag is read from the finished item.
    let count = NSPasteboard.general.changeCount
    defer { seenCount = count }
    guard count != lastCount, count == seenCount || lastCount == -1 else { return }
    lastCount = count
    var ev = PasteboardWatch.info()
    ev["event"] = "clipboard"
    ev["initial"] = first // the item that was there when watching started (not a new copy)
    first = false
    emit(ev)
  }
}
