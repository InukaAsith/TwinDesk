// Writes android/app/src/main/java/com/twindesk/android/SearchIndex.kt from shared/search-index.js:
// Search's entries for this app (with their pages as MainActivity's Tab names) and its words, so the
// phone finds what the computers find. Run: node android/tools/gen-search.js
// (shared/test/search.js checks it's up to date)
'use strict';

const fs = require('fs');
const path = require('path');
const S = require('../../shared/search-index.js');

const OUT = path.join(__dirname, '..', 'app', 'src', 'main', 'java', 'com', 'twindesk', 'android', 'SearchIndex.kt');
const q = (s) => JSON.stringify(String(s)).replace(/\$/g, '\\$');
const set = (a) => `setOf(${a.map(q).join(', ')})`;

function make() {
  const L = [];
  L.push('// TwinDesk — Copyright (C) 2026 inukaasith. GPL-3.0, see LICENSE.');
  L.push('// Generated by android/tools/gen-search.js from shared/search-index.js: don’t edit.');
  L.push('// Search’s entries (what each is called, the words people use for it, its page, which way it goes) and words.');
  L.push('package com.twindesk.android');
  L.push('');
  L.push('object SearchIndex {');
  L.push('    class Entry(val en: String, val title: () -> String, val k: String, val page: String, val dir: String)');
  L.push('');
  L.push('    val ENTRIES = listOf(');
  for (const e of S.forApp('android')) L.push(`        Entry(${q(e.t)}, { tr(${q(e.t)}) }, ${q(e.k)}, ${q(e.id)}, ${q(e.dir || '')}),`);
  L.push('    )');
  L.push('');
  const syn = Object.entries(S.SYN);
  L.push('    val SYN = mapOf(');
  for (let i = 0; i < syn.length; i += 6) L.push('        ' + syn.slice(i, i + 6).map(([a, b]) => `${q(a)} to ${q(b)}`).join(', ') + ',');
  L.push('    )');
  L.push(`    val STOP = ${set(S.STOP)}`);
  L.push(`    val TO = ${set(S.TO)}`);
  L.push(`    val LIGHT = ${set(S.LIGHT)}`);
  L.push('}');
  return L.join('\n') + '\n';
}

if (require.main === module) fs.writeFileSync(OUT, make());
module.exports = { make, OUT };
