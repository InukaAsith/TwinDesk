'use strict';
const assert = require('node:assert/strict');
const { PhonePinch } = require('../phonepinch');
const events = [];
const ctl = { closed: false, touch: (...args) => events.push(args) };
const d = { w: 1080, h: 2400, dpi: 420 }, pointer = { x: 0, y: 2399, buttons: 0 };
const p = new PhonePinch();
p.gesture(ctl, d, pointer, { phase: 'begin', v: 0 });
assert.equal(events.length, 0, 'zero movement does not plant fingers');
p.gesture(ctl, d, pointer, { phase: 'change', v: 0.15 });
assert.deepEqual(events.filter(t => t[0] === 0).map(t => t[1]), [0, 1]);
assert.ok(events[1][3] - events[0][3] >= Math.ceil(d.dpi * 1.2), 'start span exceeds Android scaling threshold');
assert.ok(events.every(t => t[2] >= 0 && t[2] < d.w && t[3] >= 0 && t[3] < d.h));
p.gesture(ctl, d, pointer, { phase: 'end', v: 0 });
assert.deepEqual(events.filter(t => t[0] === 1).map(t => t[1]), [1, 0]);
events.length = 0;
p.gesture(ctl, d, pointer, { phase: 'begin', v: -0.1 });
p.cancel();
const count = events.length;
p.gesture(ctl, d, pointer, { phase: 'change', v: 0.1 });
assert.equal(events.length, count, 'interruption blocks changes until a new gesture begins');
p.gesture(ctl, d, { ...pointer, buttons: 1 }, { phase: 'begin', v: 0.1 });
assert.equal(events.length, count, 'held mouse button prevents pinch');
console.log('phonepinch: Android-sized contacts, bounded release and interruption pass');
const T = require('../protocol').T;
for (const path of ['../../mac/phone-bridge', '../../mac/mesh/phone-bridge']) {
  const { PhoneBridge } = require(path);
  const bridge = Object.create(PhoneBridge.prototype), calls = [];
  Object.defineProperty(bridge, 'ctl', { value: { closed: false, touch: (...v) => calls.push(v), tap() {} } });
  bridge.kvm = { ...pointer, x: 540, y: 1200, mouse: true };
  bridge._display = () => d;
  bridge._move = () => { throw Error('motion must not interrupt pinch'); };
  bridge._wheel = () => { throw Error('wheel must not interrupt pinch'); };
  bridge._button = () => {};
  bridge.handle({ t: T.K_GESTURE, g: 'zoom', phase: 'begin', v: 0.1 });
  bridge.handle({ t: T.K_GESTURE, g: 'rotate', phase: 'change', v: 0.2 });
  bridge.handle({ t: T.K_MOVE, dx: 1 });
  bridge.handle({ t: T.K_WHEEL, dy: 1 });
  assert.ok(bridge.pinch.active, `${path}: rotate and motion keep the contacts`);
  bridge.handle({ t: T.K_DOWN, b: 0 });
  const count = calls.length;
  bridge.handle({ t: T.K_GESTURE, g: 'zoom', phase: 'change', v: 0.1 });
  assert.equal(calls.length, count, `${path}: interrupted contacts do not restart`);
}
const { PhoneInput } = require('../phoneinput');
const originalSet = global.setTimeout, originalClear = global.clearTimeout;
try {
  let nextId = 0;
  const timers = new Map();
  global.setTimeout = (fn, ms) => { const id = ++nextId; timers.set(id, { fn, ms }); return id; };
  global.clearTimeout = id => { timers.delete(id); };
  const messages = [], input = new PhoneInput(m => messages.push(m));
  input.pinch(540, 1200, 1080, 2400, 0.1);
  input.pinch(540, 1200, 1080, 2400, 0.2);
  const send = [...timers].find(([, timer]) => timer.ms === 180);
  timers.delete(send[0]); send[1].fn();
  assert.equal(messages.length, 1);
  assert.equal(messages[0].a, 'z');
  assert.ok(Math.abs(messages[0].v - 0.3) < 1e-9);
  input.pinch(540, 1200, 1080, 2400, 0.1);
  input.stop();
  assert.equal(timers.size, 0, 'stopping input cancels pending native pinch');
} finally { global.setTimeout = originalSet; global.clearTimeout = originalClear; }
