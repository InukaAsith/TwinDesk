// Writes ios/TwinDesk/Core/SearchIndex.swift from shared/search-index.js: Search's entries for this
// app (with their pages as RootView's Page cases) and its words, so the iPhone finds what the
// computers find. Run: node ios/tools/gen-search.js   (shared/test/search.js checks it's up to date)
'use strict';

const fs = require('fs');
const path = require('path');
const S = require('../../shared/search-index.js');

const OUT = path.join(__dirname, '..', 'TwinDesk', 'Core', 'SearchIndex.swift');
const q = (s) => JSON.stringify(String(s));
const set = (a) => `[${a.map(q).join(', ')}]`;

function make() {
  const L = [];
  L.push('// TwinDesk — Copyright (C) 2026 inukaasith. GPL-3.0, see LICENSE.');
  L.push('// Generated by ios/tools/gen-search.js from shared/search-index.js: don’t edit.');
  L.push('// Search’s entries (what each is called, the words people use for it, its page, which way it goes) and words.');
  L.push('import Foundation');
  L.push('');
  L.push('enum SearchIndex {');
  L.push('    struct Entry { let en: String; let title: () -> String; let k: String; let page: String; let dir: String }');
  L.push('');
  L.push('    static let entries: [Entry] = [');
  for (const e of S.forApp('ios')) L.push(`        Entry(en: ${q(e.t)}, title: { tr(${q(e.t)}) }, k: ${q(e.k)}, page: ${q(e.id)}, dir: ${q(e.dir || '')}),`);
  L.push('    ]');
  L.push('');
  const syn = Object.entries(S.SYN);
  L.push('    static let syn: [String: String] = [');
  for (let i = 0; i < syn.length; i += 6) L.push('        ' + syn.slice(i, i + 6).map(([a, b]) => `${q(a)}: ${q(b)}`).join(', ') + ',');
  L.push('    ]');
  L.push(`    static let stop: Set<String> = ${set(S.STOP)}`);
  L.push(`    static let to: Set<String> = ${set(S.TO)}`);
  L.push(`    static let light: Set<String> = ${set(S.LIGHT)}`);
  L.push('}');
  return L.join('\n') + '\n';
}

if (require.main === module) fs.writeFileSync(OUT, make());
module.exports = { make, OUT };
