// Writes ios/TwinDesk/Core/DeckCatalog.swift from the computer's own shared/deck-catalog.js (the
// actions' groups, names and descriptions) and shared/deck-model.js (the symbols), so the iPhone's
// Deck says what the computer's Deck page does. The symbols are drawn with SF Symbols here (SF below).
// Run: node ios/tools/gen-deck.js   (shared/test/deck-ios.js checks it's up to date)
'use strict';

const fs = require('fs');
const path = require('path');
const C = require('../../shared/deck-catalog.js');
const I = require('../../shared/deck-icons.js');
const M = require('../../shared/deck-model.js');

const OUT = path.join(__dirname, '..', 'TwinDesk', 'Core', 'DeckCatalog.swift');
const q = (s) => JSON.stringify(String(s)).replace(/\\\//g, '/');
const text = (v) => (v && typeof v === 'object' ? `[${Object.entries(v).map(([k, x]) => `${q(k)}: ${q(x)}`).join(', ')}]` : `["": ${q(v)}]`);

// The Deck's symbols as SF Symbols.
const SF = {
  play: 'play.fill', pause: 'pause.fill', next: 'forward.end.fill', prev: 'backward.end.fill', stop: 'stop.fill',
  volume: 'speaker.wave.2.fill', volumeDown: 'speaker.wave.1.fill', mute: 'speaker.slash.fill', mic: 'mic.fill', micOff: 'mic.slash.fill',
  speaker: 'hifispeaker.fill', headphones: 'headphones', bluetooth: 'antenna.radiowaves.left.and.right', sun: 'sun.max.fill', sunDim: 'sun.min.fill',
  moon: 'moon.fill', clock: 'clock', cpu: 'cpu', memory: 'memorychip', thermo: 'thermometer.medium', lock: 'lock.fill', sleep: 'moon.zzz.fill', power: 'power', desktop: 'menubar.dock.rectangle', windows: 'rectangle.3.group',
  switcher: 'arrow.left.arrow.right.square', camera: 'camera.fill', crop: 'crop', keyboard: 'keyboard', command: 'command', text: 'textformat',
  macro: 'list.bullet.indent', globe: 'globe', app: 'app.fill', folder: 'folder.fill', terminal: 'terminal.fill', copy: 'doc.on.doc.fill',
  cut: 'scissors', paste: 'doc.on.clipboard.fill', send: 'paperplane.fill', left: 'arrow.left', right: 'arrow.right', up: 'arrow.up', down: 'arrow.down',
  maximize: 'arrow.up.left.and.arrow.down.right', minimize: 'minus', display: 'display', grid: 'square.grid.2x2.fill', star: 'star.fill',
  bolt: 'bolt.fill', bell: 'bell.fill', bellOff: 'bell.slash.fill', none: 'minus',
};

function make() {
  const missing = Object.keys(I.PATHS).filter((k) => !SF[k]);
  if (missing.length) throw new Error('no SF Symbol for ' + missing.join(', '));
  const L = [];
  L.push('// TwinDesk — Copyright (C) 2026 inukaasith. GPL-3.0, see LICENSE.');
  L.push('// Generated by ios/tools/gen-deck.js from shared/deck-catalog.js and shared/deck-model.js: don’t edit.');
  L.push('// The Deck’s actions as people choose them, and its symbols (as SF Symbols), as on the computer’s Deck page.');
  L.push('import Foundation');
  L.push('');
  L.push('enum DeckCatalog {');
  L.push('    // name and desc by the computer’s platform ("" = every one); needs: a caps key that must be true.');
  L.push('    struct Entry {');
  L.push('        let id: String, group: String, names: [String: String], descs: [String: String], actionJSON: String');
  L.push('        let needs: String, local: Bool, device: Bool, wide: Bool');
  L.push('        func name(_ platform: String) -> String { names[platform] ?? names[""] ?? names["mac"] ?? "" }');
  L.push('        func desc(_ platform: String) -> String { descs[platform] ?? descs[""] ?? descs["mac"] ?? "" }');
  L.push('        var action: JSON { decodeJSON(actionJSON) ?? ["k": "none"] }');
  L.push('        var k: String { action.str("k") }');
  L.push('        var what: String? { let w = action.str("what"); return w.isEmpty ? nil : w }');
  L.push('    }');
  L.push(`    static let groups: [(String, String)] = [${C.GROUPS.map((g) => `(${q(g.id)}, ${q(g.name)})`).join(', ')}]`);
  L.push('    static let entries: [Entry] = [');
  for (const e of C.ENTRIES) {
    L.push(`        Entry(id: ${q(e.id)}, group: ${q(e.group)}, names: ${text(e.name)}, descs: ${text(e.desc)}, actionJSON: ${q(JSON.stringify(e.action))}, needs: ${q(e.needs || '')}, local: ${!!e.local}, device: ${!!e.device}, wide: ${!!e.wide}),`);
  }
  L.push('    ]');
  L.push('    // The entry an action came from (its kind, and its step when the entry has one).');
  L.push('    static func entry(_ a: JSON?) -> Entry? {');
  L.push('        guard let a = a else { return nil }');
  L.push('        let k = a.str("k"), w = a.str("what")');
  L.push('        return entries.first { $0.k == k && ($0.what == nil || $0.what == w) }');
  L.push('    }');
  L.push('    static func available(_ e: Entry, _ caps: JSON?, _ platform: String) -> String? {');
  L.push('        if e.needs.isEmpty { return nil }');
  L.push('        if let v = caps?[e.needs] as? NSNumber, !v.boolValue {');
  L.push('            if platform == "linux" && e.needs == "screenoff" { return "Not on Linux" }');
  L.push('            if platform == "linux" && e.needs == "windows" { return "Not on Wayland" }');
  L.push('            if platform == "mac" && e.needs == "dnd" { return "macOS has no switch for apps" }');
  L.push('            return "Not on this computer"');
  L.push('        }');
  L.push('        return nil');
  L.push('    }');
  L.push('');
  L.push(`    static let symbols: [String] = [${Object.keys(I.PATHS).filter((k) => k !== 'none').map(q).join(', ')}]`);
  L.push('    // A symbol as an SF Symbol; nil when it isn’t one of the Deck’s (an emoji).');
  L.push(`    static let sf: [String: String] = [${Object.keys(I.PATHS).map((k) => `${q(k)}: ${q(SF[k])}`).join(', ')}]`);
  L.push('');
  L.push('    // The symbol a tile shows when it has none of its own (shared/deck-model.js symbolOf).');
  L.push('    static func symbolOf(_ a: JSON?) -> String {');
  L.push('        let w = a?.str("what") ?? ""');
  L.push('        switch a?.str("k") ?? "" {');
  for (const k of M.KINDS) {
    const whats = M.WHATS[k];
    if (!whats) { L.push(`        case ${q(k)}: return ${q(M.symbolOf({ k }) || 'none')}`); continue; }
    const map = whats.map((x) => `${q(x)}: ${q(M.symbolOf({ k, what: x }) || 'none')}`).join(', ');
    L.push(`        case ${q(k)}: return ([${map}] as [String: String])[w] ?? ${q(M.symbolOf({ k, what: whats[0] }) || 'none')}`);
  }
  L.push('        default: return "none"');
  L.push('        }');
  L.push('    }');
  L.push('}');
  return L.join('\n') + '\n';
}

if (require.main === module) {
  fs.writeFileSync(OUT, make());
  console.log('wrote ' + path.relative(process.cwd(), OUT));
}
module.exports = { make, OUT };
